#!/usr/bin/env node
// Generates the Release notes page (src/content/docs/changelog/index.mdx) from
// the StemCounts changelog, so the help site lists what the app's own What's
// new page lists, and nothing more.
//
//     node scripts/import-changelog.mjs
//     node scripts/import-changelog.mjs --from ./changelog.json
//     node scripts/import-changelog.mjs --from ../stemcounts/CHANGELOG.md
//
// Runs as `prebuild` (package.json) beside import-support-cards.mjs. Exit code
// 1 means no source could be read; prebuild swallows that and the build uses
// the committed page.
//
// WHERE THE CHANGELOG COMES FROM, tried in this order, first success wins:
//   1. --from <path or URL>
//   2. the HELP_CHANGELOG_URL environment variable (a URL or a file path).
//   3. https://app.stemcounts.com/changelog.json, emitted by the app's Vite
//      build. Its `markdown` field is the changelog with every [Internal]
//      bullet already removed. Production, never dev.
//   4. ../stemcounts/CHANGELOG.md, the app repo's file, for a local checkout
//      with the sibling repo. Amplify has no sibling checkout.
// A .json source is read for its `markdown`, `version` and `builtAt`; anything
// else is read as the markdown itself.
//
// WHAT IS PUBLISHED. The parsing rules are those of the app's own What's new
// page (stemcounts/frontend/src/lib/releaseNotes.ts, parseChangelog and
// splitHeadline), ported line for line:
//   - a release is a `## YYYY-MM-DD · vX.Y.Z · Major|Minor|Patch` heading;
//   - a bullet is `- [Tag] text`, with indented lines continuing it;
//   - [Internal] bullets are dropped here, whatever the source, so a team-only
//     note cannot reach this page even from the raw file;
//   - only the HEADLINE (the first sentence) of a bullet is shown. The rest of
//     a bullet is the team's record and is never rendered;
//   - tags read as New, Improved and Fixed;
//   - a release whose every bullet was Internal is not shown.
//
// DETERMINISTIC apart from the "on <date>" in the GENERATED comment, which is
// the app build's date when the source carries one and today's otherwise. The
// file is only rewritten when its content changes. Node built-ins only.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_FILE = path.join(REPO, "src", "content", "docs", "changelog", "index.mdx");
const DEFAULT_URL = "https://app.stemcounts.com/changelog.json";
const LOCAL_FALLBACK = path.resolve(REPO, "..", "stemcounts", "CHANGELOG.md");
const MARKER = "GENERATED by scripts/import-changelog.mjs";
const FETCH_TIMEOUT_MS = 20000;

// ---------------------------------------------------------------------------
// Parsing (a port of releaseNotes.ts; keep the two in step)

const HEADING = /^## (\d{4}-\d{2}-\d{2}) · v(\d+\.\d+\.\d+) · (Major|Minor|Patch)$/;
const TAGGED = /^\[(Feature|Improvement|Bug|Internal)\]\s*(.*)$/s;

export const TAG_LABEL = { Feature: "New", Improvement: "Improved", Bug: "Fixed" };

/** The headline is the first sentence; the rest is detail. */
export function splitHeadline(body) {
  const m = body.match(/^(.*?[.!?])(\s+|$)/s);
  if (!m) return { headline: body.trim(), detail: "" };
  return { headline: m[1].trim(), detail: body.slice(m[0].length).trim() };
}

/** Releases, newest first, public bullets only. */
export function parseChangelog(text) {
  const releases = [];
  let current = null;
  let pending = [];

  const flush = () => {
    if (!current || pending.length === 0) return;
    const body = pending.join(" ").replace(/\s+/g, " ").trim();
    pending = [];
    const m = body.match(TAGGED);
    if (!m) return;
    const tag = m[1];
    if (tag === "Internal") return;
    const { headline } = splitHeadline(m[2]);
    if (!headline) return;
    current.bullets.push({ tag, headline });
  };

  for (const raw of String(text).split(/\r?\n/)) {
    if (raw.startsWith(">")) continue; // the preamble is quoted documentation
    const heading = raw.match(HEADING);
    if (heading) {
      flush();
      current = { date: heading[1], version: heading[2], level: heading[3], bullets: [] };
      releases.push(current);
      continue;
    }
    if (!current) continue;
    if (/^- /.test(raw)) {
      flush();
      pending.push(raw.slice(2).trim());
      continue;
    }
    if (/^\s+\S/.test(raw) && pending.length) pending.push(raw.trim());
  }
  flush();
  return releases.filter((r) => r.bullets.length > 0);
}

// ---------------------------------------------------------------------------
// Reading

const isUrl = (s) => /^https?:\/\//i.test(String(s));

async function readSource(source) {
  let text;
  if (isUrl(source)) {
    const res = await fetch(source, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    text = await res.text();
  } else {
    text = readFileSync(source, "utf8");
  }
  const looksJson = /\.json(\?|$)/i.test(source) || /^\s*\{/.test(text);
  if (!looksJson) return { markdown: text };
  const doc = JSON.parse(text);
  if (!doc || typeof doc.markdown !== "string") throw new Error("JSON has no `markdown` string");
  return doc;
}

async function loadChangelog(argv, env) {
  const candidates = [];
  const fromIdx = argv.indexOf("--from");
  if (fromIdx !== -1 && argv[fromIdx + 1]) candidates.push({ label: `--from ${argv[fromIdx + 1]}`, source: argv[fromIdx + 1] });
  if (env.HELP_CHANGELOG_URL) candidates.push({ label: `HELP_CHANGELOG_URL ${env.HELP_CHANGELOG_URL}`, source: env.HELP_CHANGELOG_URL });
  candidates.push({ label: DEFAULT_URL, source: DEFAULT_URL });
  candidates.push({ label: path.relative(REPO, LOCAL_FALLBACK).split(path.sep).join("/"), source: LOCAL_FALLBACK });

  for (const c of candidates) {
    try {
      const doc = await readSource(c.source);
      const releases = parseChangelog(doc.markdown);
      if (releases.length === 0) throw new Error("no releases could be read");
      console.log(`import-changelog: read ${releases.length} releases from ${c.label}`);
      return { ...doc, releases, source: c.label };
    } catch (err) {
      console.log(`import-changelog: ${c.label}: ${err.message}`);
    }
  }
  return null;
}

// ---------------------------------------------------------------------------
// Rendering

const yaml = (s) => JSON.stringify(String(s));

/** MDX-safe text that renders exactly as written. */
export function escapeMdxText(text) {
  return String(text)
    .replace(/</g, "&lt;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;")
    .replace(/_/g, "\\_")
    .replace(/^(\s*)([#>])/gm, "$1\\$2");
}

const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];

/** "2026-09-29" -> "29 September 2026", read as a calendar day, never through Date. */
export function longDate(iso) {
  const [y, m, d] = iso.split("-").map(Number);
  return `${d} ${MONTHS[m - 1]} ${y}`;
}

export function renderPage(releases, dateLabel) {
  const lines = [
    "---",
    `title: ${yaml("Release notes")}`,
    `description: ${yaml("What is new, improved and fixed in StemCounts, release by release.")}`,
    "sidebar:",
    "  order: 0",
    "---",
    "",
    `{/* ${MARKER} from the StemCounts changelog on ${dateLabel}; do not edit by hand */}`,
    "",
    "What has shipped in StemCounts, newest first. This is the same list the app shows",
    "under **What's new** in your menu, where you can also see the version you are on.",
    "",
  ];
  for (const r of releases) {
    lines.push(`## v${r.version}, ${longDate(r.date)}`, "");
    for (const b of r.bullets) lines.push(`- **${TAG_LABEL[b.tag]}** ${escapeMdxText(b.headline)}`);
    lines.push("");
  }
  return lines.join("\n");
}

export async function main(argv = process.argv.slice(2), env = process.env) {
  const doc = await loadChangelog(argv, env);
  if (!doc) {
    console.error("import-changelog: no source could be read; leaving the committed page as it is");
    return 1;
  }
  const dateLabel = typeof doc.builtAt === "string" && /^\d{4}-\d{2}-\d{2}/.test(doc.builtAt)
    ? doc.builtAt.slice(0, 10)
    : new Date().toISOString().slice(0, 10);

  const content = renderPage(doc.releases, dateLabel);
  mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  const changed = !existsSync(OUT_FILE) || readFileSync(OUT_FILE, "utf8") !== content;
  if (changed) writeFileSync(OUT_FILE, content, "utf8");
  const bullets = doc.releases.reduce((n, r) => n + r.bullets.length, 0);
  console.log(`import-changelog: ${doc.releases.length} releases, ${bullets} public headlines, newest v${doc.releases[0].version}; ${changed ? "wrote" : "unchanged"} src/content/docs/changelog/index.mdx`);
  return 0;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  // exitCode rather than process.exit(): exiting while fetch's sockets are still
  // closing trips a libuv assertion on Windows (Node 24) and reports exit 127.
  main().then((code) => { process.exitCode = code; }, (err) => { console.error(`import-changelog: ${err.stack || err}`); process.exitCode = 1; });
}
