#!/usr/bin/env node
// Generates the FAQ pages (src/content/docs/faqs/*.mdx) from the StemCounts
// support cards, so the help site says what the app says.
//
//     node scripts/import-support-cards.mjs
//     node scripts/import-support-cards.mjs --from ./help-cards.json
//     node scripts/import-support-cards.mjs --from https://app.stemcounts.com/help-cards.json
//
// Runs as `prebuild` (package.json), so every Amplify build refreshes the FAQ
// pages from the app's published cards. Exit code 1 means no source could be
// read; prebuild swallows that and the build uses the committed pages.
//
// WHERE THE CARDS COME FROM, tried in this order, first success wins:
//   1. --from <path or URL>
//   2. the HELP_CARDS_URL environment variable (a URL or a file path). Set it
//      in the Amplify build environment to point at a different copy, for
//      example a build of the app that is not production yet. Leave it unset
//      for production, which is what customers read.
//   3. https://app.stemcounts.com/help-cards.json, emitted by the app's Vite
//      build (stemcounts/frontend/vite-plugins/help-cards.ts). Production,
//      never dev: the site is read by production customers.
//   4. ../stemcounts/backend/api/shared/support-kb.generated.json, the app
//      repo's committed bundle, for a local checkout that has the sibling
//      repo. Amplify has no sibling checkout, so on Amplify this step fails.
//
// Both shapes carry the same card fields (id, question, audience, where, help,
// availability, answer); the URL adds version and builtAt.
//
// WHAT IS PUBLISHED. The cards carry an availability, and this script is the
// place that decides which reach a public page:
//   - admin-only cards are NEVER written. The public export already strips
//     them; the local bundle does not, so this script drops them again.
//   - live cards are written.
//   - flag:<key> cards (a feature behind a feature flag, including the
//     ":request" cards that explain how to ask for one) are written only when
//     the key is in RELEASED_FLAGS below. The app cannot tell a build whether a
//     flag is released on production, so this list is the switch. When Ben
//     releases a feature, add its key here; when he withdraws one, remove it.
//
// The answers are written verbatim: the app repo's CI checks their accuracy,
// and the only change made here is escaping for MDX and turning bare URLs into
// links. No em or en dash is ever introduced (the cards' own CI forbids them).
//
// DETERMINISTIC: same cards in, byte-identical pages out, with one exception:
// the "on <date>" in each page's GENERATED comment, which is the app build's
// date when the source carries one and today's date otherwise. Files are only
// rewritten when their content changes. Node built-ins only.
import { readFileSync, writeFileSync, readdirSync, unlinkSync, mkdirSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT_DIR = path.join(REPO, "src", "content", "docs", "faqs");
const DEFAULT_URL = "https://app.stemcounts.com/help-cards.json";
const LOCAL_FALLBACK = path.resolve(REPO, "..", "stemcounts", "backend", "api", "shared", "support-kb.generated.json");
const MARKER = "GENERATED by scripts/import-support-cards.mjs";
const FETCH_TIMEOUT_MS = 20000;

/**
 * Feature flags Ben has released on production. A flag card is published only
 * when its key is here. canva and order_texts: released 2026-09-28
 * (stemcounts/support-kb/README.md).
 */
export const RELEASED_FLAGS = ["canva", "order_texts"];

/**
 * One page per topic file in the app repo (the part of a card id before "/").
 * `order` is the sidebar order. A topic not listed here still gets a page,
 * titled from its slug, so a new topic in the app repo cannot vanish silently.
 */
const TOPICS = {
  "florist-ordering": {
    title: "Florist FAQs",
    description: "Orders, events, arrangements, the flower picker, spares, pricing and sending to your wholesaler.",
    order: 1,
  },
  wholesalers: {
    title: "Wholesaler FAQs",
    description: "The order board, accepting and confirming orders, suppliers, pick lists and your library.",
    order: 2,
  },
  "order-lifecycle-and-notifications": {
    title: "Orders, notifications and messages FAQs",
    description: "What happens to an order after it is sent, and the emails, texts and messages along the way.",
    order: 3,
  },
  "account-and-billing": {
    title: "Account and billing FAQs",
    description: "Signing in, your profile, your organisation, the trial, subscriptions, receipts and invoices.",
    order: 4,
  },
  "canva-and-platform": {
    title: "Canva, the app and platform FAQs",
    description: "Canva mood boards, finding your way around, settings, support and what has changed.",
    order: 5,
  },
  "pre-sales": {
    title: "Before you sign up",
    description: "What StemCounts is, what it costs, the free trial, who pays and how to get in touch.",
    order: 6,
  },
};

// ---------------------------------------------------------------------------
// Reading the cards

const isUrl = (s) => /^https?:\/\//i.test(String(s));

async function readSource(source) {
  if (isUrl(source)) {
    const res = await fetch(source, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS), headers: { accept: "application/json" } });
    if (!res.ok) throw new Error(`HTTP ${res.status}`);
    return JSON.parse(await res.text());
  }
  return JSON.parse(readFileSync(source, "utf8"));
}

/** Accepts both the parsed object and the raw `availability:` string. Unknown fails closed (null). */
export function normaliseAvailability(a) {
  if (a && typeof a === "object") {
    if (a.kind === "live") return { kind: "live" };
    if (a.kind === "admin") return { kind: "admin" };
    if (a.kind === "flag" && typeof a.flag === "string" && a.flag) {
      return a.request === true ? { kind: "flag", flag: a.flag, request: true } : { kind: "flag", flag: a.flag };
    }
    return null;
  }
  const v = String(a ?? "").trim();
  if (/^live\b/.test(v)) return { kind: "live" };
  if (/^admin-only\b/.test(v)) return { kind: "admin" };
  const m = /^flag:([a-z0-9_.]+?)(:request)?(?=[\s(]|$)/.exec(v);
  if (m) return m[2] ? { kind: "flag", flag: m[1], request: true } : { kind: "flag", flag: m[1] };
  return null;
}

/** Throws unless the document looks like a card bundle. */
function validate(doc, label) {
  if (!doc || typeof doc !== "object" || !Array.isArray(doc.cards)) throw new Error("no `cards` array");
  if (doc.cards.length === 0) throw new Error("zero cards");
  for (const c of doc.cards) {
    for (const f of ["id", "question", "audience", "where", "answer"]) {
      if (typeof c[f] !== "string" || !c[f].trim()) throw new Error(`card ${JSON.stringify(c.id ?? "?")} has no ${f}`);
    }
    if (!/^[a-z0-9-]+\/[a-z0-9-]+$/.test(c.id)) throw new Error(`card id ${JSON.stringify(c.id)} is not topic/slug`);
  }
  return { ...doc, source: label };
}

/** The first source that yields a valid document. */
async function loadCards(argv, env) {
  const candidates = [];
  const fromIdx = argv.indexOf("--from");
  if (fromIdx !== -1 && argv[fromIdx + 1]) candidates.push({ label: `--from ${argv[fromIdx + 1]}`, source: argv[fromIdx + 1] });
  if (env.HELP_CARDS_URL) candidates.push({ label: `HELP_CARDS_URL ${env.HELP_CARDS_URL}`, source: env.HELP_CARDS_URL });
  candidates.push({ label: DEFAULT_URL, source: DEFAULT_URL });
  candidates.push({ label: path.relative(REPO, LOCAL_FALLBACK).split(path.sep).join("/"), source: LOCAL_FALLBACK });

  for (const c of candidates) {
    try {
      const doc = validate(await readSource(c.source), c.label);
      console.log(`import-support-cards: read ${doc.cards.length} cards from ${c.label}`);
      return doc;
    } catch (err) {
      console.log(`import-support-cards: ${c.label}: ${err.message}`);
    }
  }
  return null;
}

// ---------------------------------------------------------------------------
// Filtering

/** Splits the cards into published and dropped, with the reason for each drop. */
export function selectPublic(cards, released = RELEASED_FLAGS) {
  const kept = [];
  const dropped = { admin: 0, unreleasedFlag: 0, unknown: 0 };
  for (const c of cards) {
    const a = normaliseAvailability(c.availability);
    if (!a) { dropped.unknown++; continue; }
    if (a.kind === "admin") { dropped.admin++; continue; }
    if (a.kind === "flag" && !released.includes(a.flag)) { dropped.unreleasedFlag++; continue; }
    kept.push({ ...c, availability: a });
  }
  return { kept, dropped };
}

// ---------------------------------------------------------------------------
// Rendering

/**
 * Make card text safe for MDX without changing what a reader sees. MDX treats
 * `<` as JSX and `{` `}` as expressions, a line-leading `#` or `>` as a heading
 * or quote, and `_` as emphasis; each is escaped so it renders as itself.
 * Markdown the cards use on purpose (**bold**, "- " lists, "1. " lists) is left
 * alone. URLs are escaped separately by linkify() so `_` inside them survives.
 */
export function escapeMdxText(text) {
  return String(text)
    .replace(/</g, "&lt;")
    .replace(/\{/g, "&#123;")
    .replace(/\}/g, "&#125;")
    .replace(/_/g, "\\_")
    .replace(/^(\s*)([#>])/gm, "$1\\$2");
}

const URL_RE = /https?:\/\/[^\s<>()\[\]"']+/g;

/** Bare URLs become links. Trailing sentence punctuation stays outside the link. */
export function linkify(text) {
  return String(text).replace(URL_RE, (raw, offset, whole) => {
    const before = whole.slice(Math.max(0, offset - 2), offset);
    if (before.endsWith("](") || before.endsWith("<")) return raw; // already a link
    const m = /^(.*?)([.,;:!?]*)$/.exec(raw);
    const url = m[1];
    const trail = m[2];
    return `[${url}](${url})${trail}`;
  });
}

/** Escape everything, then link URLs, un-escaping the underscores inside them. */
export function renderText(text) {
  const escaped = escapeMdxText(text);
  return linkify(escaped).replace(/\[([^\]]*)\]\(([^)]*)\)/g, (all, label, href) => {
    // Only touch links whose href is a URL we produced from the escaped text.
    if (!/^https?:\/\//.test(href)) return all;
    return `[${label.replace(/\\_/g, "_")}](${href.replace(/\\_/g, "_")})`;
  });
}

const yaml = (s) => JSON.stringify(String(s));

/** "Read more" target: the site's own pages become relative links; the home page is not worth a link. */
function readMoreHref(help) {
  if (typeof help !== "string" || !/^https?:\/\//.test(help)) return null;
  const local = help.replace(/^https:\/\/help\.stemcounts\.com/, "");
  if (local === "" || local === "/") return null;
  return local;
}

function renderCard(card) {
  const lines = [`## ${renderText(card.question)}`, "", renderText(card.answer), "", `**Where:** ${renderText(card.where)}`];
  const href = readMoreHref(card.help);
  if (href) lines.push("", `[Read more](${href})`);
  return lines.join("\n");
}

function topicMeta(slug, index) {
  if (TOPICS[slug]) return TOPICS[slug];
  const words = slug.replace(/-/g, " ");
  return {
    title: `${words.charAt(0).toUpperCase()}${words.slice(1)} FAQs`,
    description: `Answers about ${words}.`,
    order: 100 + index,
  };
}

function generatedComment(dateLabel) {
  return `{/* ${MARKER} from the StemCounts support cards on ${dateLabel}; do not edit by hand */}`;
}

export function renderPage(slug, meta, cards, dateLabel) {
  const head = [
    "---",
    `title: ${yaml(meta.title)}`,
    `description: ${yaml(meta.description)}`,
    "sidebar:",
    `  order: ${meta.order}`,
    "---",
    "",
    generatedComment(dateLabel),
    "",
    "These are the same answers the Ask StemCounts chat in the app gives, published here",
    "so you can read them without signing in. They describe the app as it is today.",
    "",
  ];
  return head.concat(cards.map(renderCard).join("\n\n")).join("\n") + "\n";
}

export function renderIndex(pages, dateLabel) {
  const lines = [
    "---",
    `title: ${yaml("FAQs")}`,
    `description: ${yaml("Quick answers to the questions florists and wholesalers ask most, grouped by topic.")}`,
    "sidebar:",
    "  order: 0",
    "---",
    "",
    generatedComment(dateLabel),
    "",
    "Quick answers, grouped by topic. Each answer is the same one the Ask StemCounts chat",
    "in the app gives, so what you read here is what the app does today.",
    "",
  ];
  for (const p of pages) {
    lines.push(`- [${p.meta.title}](/faqs/${p.slug}/): ${p.meta.description} (${p.count} ${p.count === 1 ? "answer" : "answers"})`);
  }
  return lines.join("\n") + "\n";
}

// ---------------------------------------------------------------------------
// Writing

function writeIfChanged(file, content) {
  const current = existsSync(file) ? readFileSync(file, "utf8") : null;
  if (current === content) return false;
  writeFileSync(file, content, "utf8");
  return true;
}

/** Remove generated pages this run did not produce (a topic that emptied or was renamed). Hand-written files are never touched. */
function pruneStale(keep) {
  const removed = [];
  for (const f of readdirSync(OUT_DIR)) {
    if (!f.endsWith(".mdx") || keep.has(f)) continue;
    const text = readFileSync(path.join(OUT_DIR, f), "utf8");
    if (!text.includes(MARKER)) continue;
    unlinkSync(path.join(OUT_DIR, f));
    removed.push(f);
  }
  return removed;
}

export async function main(argv = process.argv.slice(2), env = process.env) {
  const doc = await loadCards(argv, env);
  if (!doc) {
    console.error("import-support-cards: no source could be read; leaving the committed pages as they are");
    return 1;
  }

  const { kept, dropped } = selectPublic(doc.cards);
  if (kept.length === 0) {
    console.error("import-support-cards: every card was dropped; refusing to write empty pages");
    return 1;
  }

  const dateLabel = typeof doc.builtAt === "string" && /^\d{4}-\d{2}-\d{2}/.test(doc.builtAt)
    ? doc.builtAt.slice(0, 10)
    : new Date().toISOString().slice(0, 10);

  // Group by topic, in first-seen order, then sort pages by sidebar order.
  const byTopic = new Map();
  for (const c of kept) {
    const slug = c.id.split("/")[0];
    if (!byTopic.has(slug)) byTopic.set(slug, []);
    byTopic.get(slug).push(c);
  }
  const pages = [...byTopic.entries()]
    .map(([slug, cards], i) => ({ slug, cards, meta: topicMeta(slug, i), count: cards.length }))
    .sort((a, b) => a.meta.order - b.meta.order || a.slug.localeCompare(b.slug));

  mkdirSync(OUT_DIR, { recursive: true });
  const written = [];
  const keepFiles = new Set(["index.mdx"]);
  for (const p of pages) {
    const file = `${p.slug}.mdx`;
    keepFiles.add(file);
    if (writeIfChanged(path.join(OUT_DIR, file), renderPage(p.slug, p.meta, p.cards, dateLabel))) written.push(file);
    if (!TOPICS[p.slug]) console.log(`import-support-cards: WARNING topic "${p.slug}" is not in TOPICS; page titled from its slug`);
  }
  if (writeIfChanged(path.join(OUT_DIR, "index.mdx"), renderIndex(pages, dateLabel))) written.push("index.mdx");
  const removed = pruneStale(keepFiles);

  console.log(
    `import-support-cards: ${kept.length} cards on ${pages.length} pages` +
      ` (dropped ${dropped.admin} admin-only, ${dropped.unreleasedFlag} unreleased flag, ${dropped.unknown} unreadable)`,
  );
  for (const p of pages) console.log(`  ${p.slug}.mdx: ${p.count} cards, "${p.meta.title}"`);
  console.log(`import-support-cards: wrote ${written.length} file(s)${written.length ? ": " + written.join(", ") : ""}` +
    (removed.length ? `; removed stale ${removed.join(", ")}` : ""));
  return 0;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  // exitCode rather than process.exit(): exiting while fetch's sockets are still
  // closing trips a libuv assertion on Windows (Node 24) and reports exit 127.
  main().then((code) => { process.exitCode = code; }, (err) => { console.error(`import-support-cards: ${err.stack || err}`); process.exitCode = 1; });
}
